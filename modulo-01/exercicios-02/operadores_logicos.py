n1 = -5
n2 = 150

print(f"Número 1: {n1}")
print(f"Número 2: {n2}")
print(f"1. O primeiro número é maior que o segundo? {n1 > n2}")
print(f"2. Os dois são iguais? {n1 == n2}")
print(f"3. Ambos são positivos? {n1 > 0 and n2 > 0}")
print(f"4. Pelo menos um é maior que 100? {n1 > 100 or n2 > 100}")
print(f"5. O primeiro é diferente de zero? {n1 != 0}")